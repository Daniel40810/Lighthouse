-- -----------------------------------------------------------------------------------------------------
-- LH_LIGHTHOUSE: Leuchttürme. Lage als Punkt in WGS 84 (SRID 8307, Länge vor Breite).
-- -----------------------------------------------------------------------------------------------------
CREATE SEQUENCE LH_LIGHTHOUSE_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE LH_LIGHTHOUSE (
  ID             NUMBER(10) NOT NULL,
  NAME           VARCHAR2(60 CHAR) NOT NULL,
  REVIER         VARCHAR2(10) NOT NULL,
  LAGE           MDSYS.SDO_GEOMETRY NOT NULL,
  FEUERHOEHE_M   NUMBER(6,2) NOT NULL,
  TURMHOEHE_M    NUMBER(6,2),
  TRAGWEITE_SM   NUMBER(4,1),
  KENNUNG        VARCHAR2(60 CHAR) NOT NULL,
  OPTIK          VARCHAR2(10) DEFAULT 'DRUM' NOT NULL,
  BAUJAHR        NUMBER(4),
  AUSSER_BETRIEB NUMBER(4),
  STAND_JAHR     NUMBER(4) NOT NULL,
  FARBEN         VARCHAR2(200 CHAR),
  BESCHREIBUNG   VARCHAR2(1000 CHAR),
  QUELLE         VARCHAR2(600 CHAR) NOT NULL,
  HERKUNFT       VARCHAR2(12) DEFAULT 'EIGEN' NOT NULL,
  ANGELEGT       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  GEAENDERT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT LH_LIGHTHOUSE_PK PRIMARY KEY (ID),
  CONSTRAINT LH_LIGHTHOUSE_UK UNIQUE (NAME),
  CONSTRAINT LH_LIGHTHOUSE_REVIER_CK CHECK (REVIER IN ('NORDSEE','OSTSEE')),
  CONSTRAINT LH_LIGHTHOUSE_OPTIK_CK CHECK (OPTIK IN ('DRUM','ROTATING')),
  CONSTRAINT LH_LIGHTHOUSE_HERKUNFT_CK CHECK (HERKUNFT IN ('MITGELIEFERT','EIGEN'))
);

CREATE OR REPLACE TRIGGER LH_LIGHTHOUSE_BIU
BEFORE INSERT OR UPDATE ON LH_LIGHTHOUSE
FOR EACH ROW
BEGIN
  IF INSERTING THEN
    IF :NEW.ID IS NULL THEN
      :NEW.ID := LH_LIGHTHOUSE_SEQ.NEXTVAL;
    END IF;
    :NEW.ANGELEGT := NVL(:NEW.ANGELEGT, SYSTIMESTAMP);
  END IF;
  :NEW.GEAENDERT := SYSTIMESTAMP;
END;
/

